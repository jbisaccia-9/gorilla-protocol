    private int levelIndex;

    public LevelMap(int levelIndex) {
        this.levelIndex = levelIndex;
    }

    public void setLevelIndex(int levelIndex) {
        this.levelIndex = Math.max(0, Math.min(levelIndex, LEVELS.length - 1));
    }

    public int getLevelCount() {
        return LEVELS.length;
    }

    public boolean isWall(double x, double y) {
        int mapX = (int) x;
        int mapY = (int) y;
        if (mapX < 0 || mapY < 0 || mapX >= GameConstants.MAP_WIDTH || mapY >= GameConstants.MAP_HEIGHT) {
            return true;
        }
        return LEVELS[levelIndex][mapY][mapX] != 0;
    }

    public int getTile(int x, int y) {
        if (x < 0 || y < 0 || x >= GameConstants.MAP_WIDTH || y >= GameConstants.MAP_HEIGHT) {
            return 1;
        }
        return LEVELS[levelIndex][y][x];
    }
